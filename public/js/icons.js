window.icons = {
  allEntries() {
    const list = [];
    for (const [id, info] of Object.entries(window.ICON_LIBRARY)) {
      list.push({ id, title: info.title, aliases: info.aliases || [], color: info.color });
      for (const a of (info.aliases || [])) {
        list.push({ id, title: info.title, aliases: [], matchAlias: a, color: info.color });
      }
    }
    return list;
  },

  url(id) {
    return `https://cdn.jsdelivr.net/npm/simple-icons@11/icons/${id}.svg`;
  },

  dashboardUrl(name, format = 'png', variant = '') {
    const base = name.toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-|-$/g, '');
    if (!base) return '';
    const suffix = variant ? `-${variant}` : '';
    return `https://cdn.jsdelivr.net/gh/homarr-labs/dashboard-icons/${format}/${base}${suffix}.${format}`;
  },

  getInfo(id) {
    return window.ICON_LIBRARY[id] || null;
  },

  detectFromUrl(url, title) {
    if (!url && !title) return null;
    const haystack = `${url || ''} ${title || ''}`.toLowerCase();
    const tokens = new Set(haystack.split(/[^a-z0-9]+/).filter(Boolean));

    for (const [id, info] of Object.entries(window.ICON_LIBRARY)) {
      if (tokens.has(id)) return id;
      for (const a of (info.aliases || [])) {
        if (tokens.has(a)) return id;
      }
    }

    for (const [id, info] of Object.entries(window.ICON_LIBRARY)) {
      if (id.length >= 4 && haystack.includes(id)) return id;
      for (const a of (info.aliases || [])) {
        if (a.length >= 4 && haystack.includes(a)) return id;
      }
    }
    return null;
  },

  parse(iconValue) {
    if (!iconValue) return { type: 'emoji', value: '🔗', url: '', label: '🔗' };
    if (/^https?:\/\//.test(iconValue)) {
      return { type: 'url', value: iconValue, url: iconValue, label: 'Bild-URL' };
    }
    if (iconValue.startsWith('simpleicon:')) {
      const id = iconValue.slice('simpleicon:'.length);
      const info = window.ICON_LIBRARY[id];
      return {
        type: 'simpleicon', value: iconValue, url: this.url(id),
        label: info?.title || id
      };
    }
    if (iconValue.startsWith('dashboardicon:')) {
      const raw = iconValue.slice('dashboardicon:'.length);
      const [name, format = 'png', variant = ''] = raw.split(':');
      return {
        type: 'dashboardicon', value: iconValue,
        url: this.dashboardUrl(name, format || 'png', variant || ''),
        label: name
      };
    }
    return { type: 'emoji', value: iconValue, url: '', label: iconValue };
  }
};
